//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"reflect"
	"runtime"
	"slices"
	"strconv"
	"strings"

	"github.com/jesseduffield/lazygit/pkg/config"
)

func main() {
	_, source, _, _ := runtime.Caller(0)
	directory := filepath.Dir(source)
	root := filepath.Clean(filepath.Join(directory, "../../.."))
	fields := map[string][]string{}
	alternates := map[string][]string{}
	fset := token.NewFileSet()
	text := func(node ast.Node) string {
		var b bytes.Buffer
		if err := format.Node(&b, fset, node); err != nil {
			panic(err)
		}
		return b.String()
	}
	add := func(target map[string][]string, key, value string) {
		if !slices.Contains(target[key], value) {
			target[key] = append(target[key], value)
		}
	}
	err := filepath.WalkDir(filepath.Join(root, "pkg/gui"), func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return err
		}
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		// A literal with a stable ID and keys is a binding or menu action source.
		// Dynamic IDs inherit provenance from their static fallback binding ID.
		ast.Inspect(file, func(node ast.Node) bool {
			literal, ok := node.(*ast.CompositeLit)
			if !ok {
				return true
			}
			id := ""
			var keys ast.Expr
			for _, element := range literal.Elts {
				field, ok := element.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				name, ok := field.Key.(*ast.Ident)
				if !ok {
					continue
				}
				if name.Name == "CommandID" {
					if value, ok := field.Value.(*ast.BasicLit); ok && value.Kind == token.STRING {
						id, _ = strconv.Unquote(value.Value)
					}
				}
				if name.Name == "Keys" {
					keys = field.Value
				}
			}
			if id != "" && keys != nil {
				ast.Inspect(keys, func(node ast.Node) bool {
					selector, ok := node.(*ast.SelectorExpr)
					if ok {
						path, ok := strings.CutPrefix(text(selector), "opts.Config.")
						if ok && isKeyField(path) {
							add(fields, id, path)
						}
					}
					return true
				})
			}
			return true
		})
		return nil
	})
	if err != nil {
		panic(err)
	}
	file, err := parser.ParseFile(fset, filepath.Join(root, "pkg/config/user_config.go"), nil, 0)
	if err != nil {
		panic(err)
	}
	ast.Inspect(file, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if ok && text(call.Fun) == "mergeLegacyAlt" && len(call.Args) == 2 {
			primary := strings.TrimPrefix(text(call.Args[0]), "&c.")
			alternate := strings.TrimPrefix(text(call.Args[1]), "c.")
			if isKeyField(primary) && isKeyField(alternate) {
				add(alternates, primary, alternate)
			}
		}
		return true
	})
	var output bytes.Buffer
	output.WriteString("// Code generated by generate_legacy.go; DO NOT EDIT.\n\npackage keymap\n\n")
	for _, item := range []struct {
		name string
		data map[string][]string
	}{{"legacyFields", fields}, {"legacyAlternates", alternates}} {
		fmt.Fprintf(&output, "var %s = map[string][]string{\n", item.name)
		keys := make([]string, 0, len(item.data))
		for key := range item.data {
			keys = append(keys, key)
		}
		slices.Sort(keys)
		for _, key := range keys {
			fmt.Fprintf(&output, "%q: {", key)
			for _, field := range item.data[key] {
				fmt.Fprintf(&output, "%q,", field)
			}
			output.WriteString("},\n")
		}
		output.WriteString("}\n\n")
	}
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(directory, "legacy_fields_generated.go"), formatted, 0o644); err != nil {
		panic(err)
	}
}

func isKeyField(path string) bool {
	typeOf := reflect.TypeFor[config.KeybindingConfig]()
	for _, name := range strings.Split(path, ".") {
		if typeOf.Kind() != reflect.Struct {
			return false
		}
		field, ok := typeOf.FieldByName(name)
		if !ok {
			return false
		}
		typeOf = field.Type
	}
	return typeOf == reflect.TypeFor[config.Keybinding]() || typeOf == reflect.TypeFor[[]config.Keybinding]()
}
